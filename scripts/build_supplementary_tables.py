# Build the ePRS_Comp supplementary tables as CSVs, combined across phenotypes.
#
# The tables are written as data rather than embedded in the manuscript so they
# can be regenerated when an analysis is re-run, and so the two phenotypes sit
# in one file with a phenotype column rather than in separate blocks that have
# to be kept in step by hand.
#
#   S3   combining weights of the fitted ePRS_Comp model, per encoding
#   S5   nested reclassification of a clinical model with and without ePRS_Comp
#   (unnumbered) operating characteristics at matched flag rates, including the
#        rule-based composite at its own deployed threshold. Not cited in the
#        manuscript, so it carries no S number; supporting data only.
#
# Column definitions are written alongside as a notes file, since a CSV cannot
# carry footnotes and the columns are not self-explanatory: several of them
# only mean what they appear to mean under a stated comparison discipline.

import argparse
import os

import pandas as pd

PHENOS = [('type2Diabetes', 'T2D'), ('celiacDisease', 'CD')]
CLIN = 'clinicalMeasures'

NOTES = """# Supplementary table column definitions

Generated by `scripts/build_supplementary_tables.py`. One row per phenotype and
per model; the `phenotype` column separates T2D from CD throughout.

## Extended Table S3 — fitted ePRS_Comp combining weights

| column | meaning |
|---|---|
| `phenotype` | T2D or CD. |
| `encoding` | The ePRS model carrying this weight. Only models retained as statistically distinct for that phenotype were entered: five for T2D, three for CD, PRS_G+G and PRS_GxGxE having been excluded in CD as redundant. |
| `coefficient` | Logistic regression coefficient on the log-odds scale. Scores were standardised using validation-cohort means and standard deviations, so coefficients are comparable with one another: one twice another indicates twice the contribution per standard deviation of that score. |
| `se`, `ci_low`, `ci_high` | Standard error and 95% Wald confidence interval. |
| `p_value` | Wald test. The intercept reflects disease prevalence and is not interpreted. |

Weights were estimated in the validation cohort alone (n=67,402 T2D; n=67,404
CD) and the fitted model applied once to the holdout, which contributed to
neither the standardisation nor the weights.

## Extended Table S5 — nested reclassification, clinical model +/- ePRS_Comp

Each row compares a clinical model with the same model plus ePRS_Comp; the two
arms differ only by that term.

| column | meaning |
|---|---|
| `phenotype` | T2D or CD. The T2D comparison is independent: none of HbA1c, BMI or glucose is an input to the retained gene-environment features, whose 14 environmental terms are other cardiometabolic and haematological measures. In CD one of the three measures, haemoglobin concentration, is an input to the retained G+GxE model, so those rows are reported for completeness rather than as a clean comparison. |
| `model` | Which clinical measures the reference model contains. Every model also includes age and sex. Ancestry principal components are in neither arm, since they are not clinical and including them only alongside ePRS_Comp would credit the genetic score with ancestry adjustment. |
| `auc_clinical`, `auc_clinical_plus_eprs` | AUC of each arm from pooled out-of-fold predictions, 5-fold stratified cross-validation. |
| `delta_auc`, `delong_p` | Difference and DeLong test for two correlated ROC curves. |
| `nri` | Net reclassification improvement. Both arms are binarised at the SAME threshold, the reference model's 80th percentile of predicted risk, so the classification budget is set once by the clinical model and ePRS_Comp must earn reclassification rather than being allocated a larger share of the cohort. |
| `nri_events`, `nri_non_events` | Event and non-event components, which sum to `nri`. |
| `idi` | Integrated discrimination improvement: gain in mean predicted-risk separation between cases and controls. Reported because it requires no threshold. |
| `cfnri` | Category-free NRI, which also requires no threshold. Its event component is large in every row including those where delta AUC is null, because it counts only the direction any risk moves; it is not a headline quantity. |
| `nri_at_youden`, `youden_flag_rate` | The same NRI at the reference model's Youden point, retained for reference. Youden weights a missed case and a false alarm equally and flags a different fraction of the cohort for every model, so it is not used as the primary threshold. |

T2D values are small because the clinical model already identifies most cases:
age, sex, HbA1c, BMI and glucose flag 79% of them from 17% of the cohort,
leaving little for any score to add.

## Operating characteristics at matched flag rates (uncited supporting data)

| column | meaning |
|---|---|
| `phenotype` | T2D or CD. |
| `score` | Fitted ensemble (ePRS_Comp), rule-based composite, PRS_G, or a reference row. |
| `target_flag_rate` | The share of the cohort the score was set to flag. Blank for the deployed rule, whose operating point is not chosen: it falls out of the union of five top-20% flags. |
| `flagged`, `flag_rate` | Individuals flagged, and that as a proportion. |
| `auc` | AUC of the score itself. |
| `sensitivity`, `specificity`, `ppv`, `npv` | At that flag rate. |
| `enrichment` | PPV divided by cohort prevalence: the factor by which flagging concentrates cases over flagging at random. A value near 1 means the rule adds little over no model at all. |
| `cases_caught` | Cases among the flagged. |

The `rule-based composite, binary flag (as deployed)` row uses bin > 800. Bins
run 1-1000, so the top fifth is 801-1000; the stored `combined_high_risk`
column uses >= 800 and also admits bin 800, which belongs to the eighth decile.
The `flag everyone (no model)` row is the reference against which enrichment
should be read.
"""


def collect(filename, out_name, out_dir, drop=()):
    frames = []
    for pheno, label in PHENOS:
        path = os.path.join('results', pheno, 'combinedAnalysis', 'scores',
                            CLIN, filename)
        if not os.path.exists(path):
            print(f'  [skip] {label}: {path} not found')
            continue
        d = pd.read_csv(path)
        d.insert(0, 'phenotype', label)
        frames.append(d)
        print(f'  {label}: {len(d)} rows')
    if not frames:
        return None
    out = pd.concat(frames, ignore_index=True)
    out = out.drop(columns=[c for c in drop if c in out.columns])
    dest = os.path.join(out_dir, out_name)
    out.to_csv(dest, index=False)
    print(f'  -> {dest} ({len(out)} rows, {len(out.columns)} columns)\n')
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out_dir', required=True)
    args = ap.parse_args()
    os.makedirs(args.out_dir, exist_ok=True)

    print('S3 fitted ensemble combining weights')
    collect('fitted_prs_ensemble_coefficients.csv',
            'ExtendedTableS3_ensemble_coefficients.csv', args.out_dir)

    print('S5 nested reclassification')
    collect('nested_nri_clinical_eprs.csv',
            'ExtendedTableS5_nested_reclassification.csv', args.out_dir,
            drop=('clinical_terms', 'se', 'threshold'))

    print('operating characteristics')
    collect('fitted_prs_ensemble_operating.csv',
            'operating_characteristics.csv', args.out_dir)

    notes = os.path.join(args.out_dir, 'ExtendedTables_S3_S5_notes.md')
    with open(notes, 'w') as fh:
        fh.write(NOTES)
    print(f'-> {notes}')


if __name__ == '__main__':
    main()
